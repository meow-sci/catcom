namespace KsaScripting.Core.Api;

/// <summary>
///     Generates the editor stubs for scripts from the <see cref="ApiSchema"/>: TypeScript declarations,
///     LuaCATS annotations, and the language-server project files that make an editor pick them up.
///     All output is deterministic and uses <c>"\n"</c> line endings.
/// </summary>
public static class StubGenerators
{
    /// <summary>The header line of both stub files.</summary>
    internal const string GeneratedNotice = "Generated by ksa-scripting — do not edit; regenerated on every mod start.";

    /// <summary>
    ///     Generates <c>stubs/host.d.ts</c>: <c>declare namespace ksa { ... }</c> with every class as an
    ///     interface (the <c>ksa</c> module's own members as <c>const</c>/<c>function</c> declarations), JSDoc
    ///     from the schema, and <c>declare module "ksa"</c> so both the global <c>ksa</c> and
    ///     <c>import { ksa } from "ksa"</c> type-check.
    /// </summary>
    /// <param name="classes">The classes to declare (normally <see cref="ApiSchema.Classes"/>).</param>
    /// <returns>The file text, <c>"\n"</c>-terminated.</returns>
    public static string TypeScriptDeclarations(IReadOnlyList<ApiClass> classes)
    {
        ArgumentNullException.ThrowIfNull(classes);
        return TypeScriptEmitter.Emit(classes);
    }

    /// <summary>
    ///     Generates <c>stubs/ksa.lua</c>: LuaCATS (<c>---@class</c>, <c>---@field</c>, <c>---@param</c>,
    ///     <c>---@return</c>, <c>---@async</c>) stubs with snake_case names, for the Lua language server.
    /// </summary>
    /// <param name="classes">The classes to declare (normally <see cref="ApiSchema.Classes"/>).</param>
    /// <returns>The file text, <c>"\n"</c>-terminated.</returns>
    public static string LuaCats(IReadOnlyList<ApiClass> classes)
    {
        ArgumentNullException.ThrowIfNull(classes);
        return LuaCatsEmitter.Emit(classes);
    }

    /// <summary>Generates <c>tsconfig.json</c> for the scripts folder (strict, ES2022, bundler resolution, the generated stub included).</summary>
    /// <returns>The file text, <c>"\n"</c>-terminated.</returns>
    public static string TsConfigJson()
        => """
           {
             "compilerOptions": {
               "target": "es2022",
               "module": "esnext",
               "moduleResolution": "bundler",
               "strict": true,
               "noEmit": true,
               "lib": ["es2022"],
               "types": [],
               "skipLibCheck": true
             },
             "include": ["**/*.ts", "stubs/host.d.ts"],
             "exclude": ["node_modules"]
           }

           """.ReplaceLineEndings("\n");

    /// <summary>Generates <c>.luarc.json</c> for the scripts folder (LuaJIT runtime, the stubs folder as a library, <c>ksa</c> as a known global).</summary>
    /// <returns>The file text, <c>"\n"</c>-terminated.</returns>
    public static string LuaRcJson()
        => """
           {
             "$schema": "https://raw.githubusercontent.com/LuaLS/vscode-lua/master/setting/schema.json",
             "runtime": {
               "version": "LuaJIT"
             },
             "workspace": {
               "library": ["stubs"],
               "checkThirdParty": false
             },
             "diagnostics": {
               "globals": ["ksa"]
             }
           }

           """.ReplaceLineEndings("\n");
}
