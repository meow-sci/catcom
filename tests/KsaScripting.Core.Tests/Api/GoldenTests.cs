using KsaScripting.Core.Api;

namespace KsaScripting.Core.Tests.Api;

/// <summary>
///     Pins the generated stubs byte-for-byte. After an intentional schema change, regenerate the
///     golden files with <c>KSA_UPDATE_GOLDEN=1 dotnet test tests/KsaScripting.Core.Tests --filter FullyQualifiedName~Golden</c>
///     and review the diff.
/// </summary>
[TestFixture]
public sealed class GoldenTests
{
    private static bool UpdateGolden => Environment.GetEnvironmentVariable("KSA_UPDATE_GOLDEN") == "1";

    private static string Normalize(string text) => text.Replace("\r\n", "\n", StringComparison.Ordinal);

    private static void Verify(string goldenFile, string actual)
    {
        if (UpdateGolden)
        {
            Directory.CreateDirectory(RepoPaths.GoldenSourceDirectory);
            File.WriteAllText(Path.Combine(RepoPaths.GoldenSourceDirectory, goldenFile), actual);
            Assert.Pass($"Golden file {goldenFile} regenerated.");
        }

        var path = Path.Combine(TestContext.CurrentContext.TestDirectory, "Golden", goldenFile);
        Assert.That(File.Exists(path), Is.True, $"Missing golden file {path}; run with KSA_UPDATE_GOLDEN=1 to create it.");
        Assert.That(actual, Is.EqualTo(Normalize(File.ReadAllText(path))), $"{goldenFile} differs from the generator output; run with KSA_UPDATE_GOLDEN=1 after reviewing the change.");
    }

    [Test]
    public void TypeScriptDeclarations_MatchGolden()
        => Verify("host.d.ts", StubGenerators.TypeScriptDeclarations(ApiSchema.Classes));

    [Test]
    public void LuaCats_MatchGolden()
        => Verify("ksa.lua", StubGenerators.LuaCats(ApiSchema.Classes));

    [Test]
    public void TsConfigJson_MatchesGolden()
        => Verify("tsconfig.json", StubGenerators.TsConfigJson());

    [Test]
    public void LuaRcJson_MatchesGolden()
        => Verify("luarc.json", StubGenerators.LuaRcJson());

    [Test]
    public void GeneratedOutput_UsesUnixLineEndings_AndEndsWithNewline()
    {
        var outputs = new[]
        {
            StubGenerators.TypeScriptDeclarations(ApiSchema.Classes),
            StubGenerators.LuaCats(ApiSchema.Classes),
            StubGenerators.TsConfigJson(),
            StubGenerators.LuaRcJson(),
        };
        foreach (var text in outputs)
        {
            Assert.That(text, Does.Not.Contain("\r"));
            Assert.That(text, Does.EndWith("\n"));
            Assert.That(text, Does.Not.EndWith("\n\n"));
        }
    }

    [Test]
    public void TypeScriptDeclarations_DeclareBothTheGlobalAndTheModule()
    {
        var text = StubGenerators.TypeScriptDeclarations(ApiSchema.Classes);
        Assert.Multiple(() =>
        {
            Assert.That(text, Does.StartWith("// Generated by ksa-scripting"));
            Assert.That(text, Does.Contain("declare namespace ksa {"));
            Assert.That(text, Does.Contain("declare module \"ksa\" {"));
            Assert.That(text, Does.Contain("type EventName ="));
            Assert.That(text, Does.Contain("| (string & {});"));
            Assert.That(text, Does.Contain("Action: `vessel.throttle` (Frame)"));
            Assert.That(text, Does.Contain("Action: `vessel.attitude_mode` (Solver)"));
            Assert.That(text, Does.Contain("setAttitudeMode(m: string): Promise<CommandResult>;"));
            Assert.That(text, Does.Not.Contain("function export("));
        });
    }

    [Test]
    public void LuaCats_UseSnakeCaseAndLuaSpecificNames()
    {
        var text = StubGenerators.LuaCats(ApiSchema.Classes);
        Assert.Multiple(() =>
        {
            Assert.That(text, Does.StartWith("---@meta ksa"));
            Assert.That(text, Does.Contain("function VesselRef:set_throttle(f) end"));
            Assert.That(text, Does.Contain("function ksa.wait_until(pred, opts) end"));
            Assert.That(text, Does.Contain("function ksa.wait_event(name, opts) end"));
            Assert.That(text, Does.Contain("function ksa.export(name, fn) end"));
            Assert.That(text, Does.Contain("---@class ksa.EngineRef : ksa.EngineInfo"));
            Assert.That(text, Does.Contain("---@field vac_thrust_n number"));
            Assert.That(text, Does.Contain("---@async"));
            Assert.That(text, Does.Contain("---@alias ksa.EventName"));
            Assert.That(text, Does.Not.Contain("function ksa.until("));
            Assert.That(text, Does.Not.Contain("vacThrustN"));
            Assert.That(text, Does.EndWith("return ksa\n"));
        });
    }
}
